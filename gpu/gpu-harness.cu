/* The GPU version of harness.c. The including file must define

   - state_t, the type of the state of a generator;
   - INIT(s, seed), a statement initializing the state s using the uint64_t
     variable seed (splitmix64(&seed) returns successive outputs of SplitMix);
   - next(state_t *s), a __device__ function returning the next output, unless
     it defines ACCUMULATE(e, s) (see below).

   Every thread copies its state into registers, accumulates the outputs of
   ITERATIONS calls, and writes the result to global memory, so that the
   computation cannot be eliminated. Outputs are accumulated with a xor, or
   with an addition if HARNESS_ADD is defined: as in harness.c, the operation
   must differ from the last operation of the output. RESULT_T (default
   uint32_t) is the type of the outputs, and WORDS (default the number of
   32-bit words in RESULT_T) is the number of 32-bit words returned by each
   call; a generator returning several words per call, such as Philox through
   curand4(), defines WORDS and ACCUMULATE(e, s) accordingly.

   States are initialized by a separate kernel, which is not timed. Time is
   measured with CUDA events, and speed is reported in the format of harness.c,
   but counting 32-bit words (harness.c counts 64-bit words) generated by all
   threads. By default there are 256 threads per
   block, and as many blocks as the multiprocessors can run at the same time,
   given the registers used by the kernel: all threads run in a single wave, so
   the time does not include a tail in which some multiprocessors are idle or
   partially occupied. */

#include <stdio.h>
#include <stdint.h>
#include <stdlib.h>

#ifndef RESULT_T
#define RESULT_T uint32_t
#endif

#ifndef WORDS
#define WORDS (sizeof(RESULT_T) / 4)
#endif

/* GPUs issue instructions in order, so loop control, which out-of-order CPUs
   overlap with the dependency chain of the generator, costs about as much as
   the step of a cheap generator: unlike cpu/build.sh, which uses
   -fno-unroll-loops, we unroll the loop UNROLL times (default 16; UNROLL=1
   disables unrolling). */
#ifndef UNROLL
#define UNROLL 16
#endif

#define PRAGMA(x) _Pragma(#x)
#define UNROLL_LOOP(n) PRAGMA(unroll n)

#ifndef ACCUMULATE
#ifdef HARNESS_ADD
#define ACCUMULATE(e, s) e += next(&s)
#else
#define ACCUMULATE(e, s) e ^= next(&s)
#endif
#endif

#define CHECK(call) do { \
	const cudaError_t err = (call); \
	if (err != cudaSuccess) { \
		fprintf(stderr, "%s:%d: %s\n", __FILE__, __LINE__, cudaGetErrorString(err)); \
		exit(1); \
	} \
} while(0)

__device__ static inline uint64_t splitmix64(uint64_t *x) {
	uint64_t z = (*x += 0x9e3779b97f4a7c15);
	z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9;
	z = (z ^ (z >> 27)) * 0x94d049bb133111eb;
	return z ^ (z >> 31);
}

__global__ void init_states(state_t *states) {
	const uint64_t tid = blockIdx.x * (uint64_t)blockDim.x + threadIdx.x;
	uint64_t seed = tid;
	state_t s;
	INIT(s, seed);
	states[tid] = s;
}

__global__ void generate(state_t *states, const uint32_t n, RESULT_T *out) {
	const uint64_t tid = blockIdx.x * (uint64_t)blockDim.x + threadIdx.x;
	state_t s = states[tid];
	RESULT_T e = 0;
	UNROLL_LOOP(UNROLL)
	for(uint32_t i = n; i-- != 0;) {
		ACCUMULATE(e, s); // Measurement
	}
	out[tid] = e;
}

int main(int argc, char* argv[]) {
	if (argc < 2 || argc > 4) {
		fprintf(stderr, "USAGE: %s ITERATIONS [THREADS [BLOCKS]]\n", argv[0]);
		fprintf(stderr, "ITERATIONS is the number of calls per thread.\n");
		exit(1);
	}
	const unsigned long long arg = strtoull(argv[1], NULL, 0);
	if (arg == 0 || arg > UINT32_MAX) {
		fprintf(stderr, "ITERATIONS must be between 1 and %u\n", UINT32_MAX);
		exit(1);
	}
	const uint32_t n = arg;

	cudaDeviceProp prop;
	CHECK(cudaGetDeviceProperties(&prop, 0));
	const int threads = argc > 2 ? atoi(argv[2]) : 256;
	int blocks_per_sm;
	if (threads <= 0 || threads > prop.maxThreadsPerBlock) {
		fprintf(stderr, "THREADS must be between 1 and %d\n", prop.maxThreadsPerBlock);
		exit(1);
	}
	CHECK(cudaOccupancyMaxActiveBlocksPerMultiprocessor(&blocks_per_sm, generate, threads, 0));
	if (blocks_per_sm == 0) {
		fprintf(stderr, "Blocks of %d threads do not fit on a multiprocessor with the registers used by the kernel\n", threads);
		exit(1);
	}
	const int blocks = argc > 3 ? atoi(argv[3]) : prop.multiProcessorCount * blocks_per_sm;
	const uint64_t total = (uint64_t)blocks * threads;

	state_t *states;
	RESULT_T *out;
	CHECK(cudaMalloc(&states, total * sizeof(state_t)));
	CHECK(cudaMalloc(&out, total * sizeof(RESULT_T)));

	init_states<<<blocks, threads>>>(states);
	CHECK(cudaGetLastError());
	CHECK(cudaDeviceSynchronize());

	cudaEvent_t start, stop;
	CHECK(cudaEventCreate(&start));
	CHECK(cudaEventCreate(&stop));
	CHECK(cudaEventRecord(start));
	generate<<<blocks, threads>>>(states, n, out);
	CHECK(cudaEventRecord(stop));
	CHECK(cudaEventSynchronize(stop));
	CHECK(cudaGetLastError());

	float ms;
	CHECK(cudaEventElapsedTime(&ms, start, stop));
	const double time_delta = ms * 1E6; // ns
	const double words = (double)total * n * WORDS;
	printf("%s: %.03f s, %.03f GB/s, %.03f words/ns, %.03e ns/word (%s, %d blocks x %d threads, at most %d blocks per multiprocessor)\n", argv[0], time_delta / 1E9, (words * 4) / time_delta, words / time_delta, time_delta / words, prop.name, blocks, threads, blocks_per_sm);

	CHECK(cudaFree(states));
	CHECK(cudaFree(out));
	return 0;
}
